namespace SixLabors.ImageSharp.Drawing.Svg;

/// <summary>
/// The value of the <c>text-decoration-style</c> property.
/// </summary>
internal enum SvgTextDecorationStyle : byte
{
    /// <summary>
    /// <c>solid</c>, the initial value.
    /// </summary>
    Solid,

    /// <summary>
    /// <c>double</c>.
    /// </summary>
    Double,

    /// <summary>
    /// <c>dotted</c>.
    /// </summary>
    Dotted,

    /// <summary>
    /// <c>dashed</c>.
    /// </summary>
    Dashed,

    /// <summary>
    /// <c>wavy</c>.
    /// </summary>
    Wavy
}
